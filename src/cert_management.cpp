// Combined trust bundle handed to mbedTLS. When a LittleFS override exists,
// this is DEFAULT_ROOT_CA_CERT + override concatenated; mbedTLS parses every
// PEM block in the buffer as a separate trust anchor, so the handshake
// succeeds if the server's chain validates against either one. When no
// override is present, this is left empty and getRootCACert() returns the
// embedded default directly (no extra RAM copy).
static String trustBundle;

static bool looksLikeValidPem(const String &pem) {
    if (pem.length() < 200 || pem.length() > ROOT_CA_MAX_SIZE) {
        return false;
    }
    if (pem.indexOf("-----BEGIN CERTIFICATE-----") < 0) {
        return false;
    }
    if (pem.indexOf("-----END CERTIFICATE-----") < 0) {
        return false;
    }
    return true;
}

// Build the combined trust bundle from the embedded default plus the given
// override PEM. Always puts the embedded default first so that, if the
// override is somehow malformed in a way that survived looksLikeValidPem(),
// mbedTLS still parses the default and the handshake can succeed against it.
static void rebuildTrustBundle(const String &overridePem) {
    if (overridePem.length() == 0) {
        trustBundle = "";  // signal to getRootCACert() to return default ptr
        return;
    }
    trustBundle.reserve(strlen(DEFAULT_ROOT_CA_CERT) + overridePem.length() + 2);
    trustBundle = DEFAULT_ROOT_CA_CERT;
    if (!trustBundle.endsWith("\n")) {
        trustBundle += '\n';
    }
    trustBundle += overridePem;
}

void initCertManagement() {
    trustBundle = "";

    if (!LittleFS.exists(ROOT_CA_FILE_PATH)) {
        Serial.println("CertMgr: no override file, using embedded default only");
        return;
    }

    File f = LittleFS.open(ROOT_CA_FILE_PATH, "r");
    if (!f) {
        Serial.println("CertMgr: failed to open override file, using default only");
        return;
    }

    String contents = f.readString();
    f.close();

    if (!looksLikeValidPem(contents)) {
        Serial.println("CertMgr: override file invalid PEM, using default only");
        return;
    }

    rebuildTrustBundle(contents);
    Serial.print("CertMgr: trust bundle = default + override, total length=");
    Serial.println(trustBundle.length());
}

const char *getRootCACert() {
    if (trustBundle.length() > 0) {
        return trustBundle.c_str();
    }
    return DEFAULT_ROOT_CA_CERT;
}

bool updateRootCACert(const String &pemCert) {
    if (!looksLikeValidPem(pemCert)) {
        Serial.println("CertMgr: updateRootCACert rejected - invalid PEM");
        return false;
    }

    File f = LittleFS.open(ROOT_CA_FILE_PATH, "w");
    if (!f) {
        Serial.println("CertMgr: failed to open override file for write");
        return false;
    }

    size_t written = f.print(pemCert);
    f.close();

    if (written != pemCert.length()) {
        Serial.println("CertMgr: short write to override file");
        return false;
    }

    rebuildTrustBundle(pemCert);
    Serial.print("CertMgr: override cert updated, bundle length=");
    Serial.println(trustBundle.length());
    return true;
}

bool resetRootCACert() {
    trustBundle = "";
    if (LittleFS.exists(ROOT_CA_FILE_PATH)) {
        return LittleFS.remove(ROOT_CA_FILE_PATH);
    }
    return true;
}
